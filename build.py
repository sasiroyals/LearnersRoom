#!/usr/bin/env python3
"""Build Learners Room into one static page.

    python build.py           writes index.html (what GitHub Pages serves)
    python build.py --check   fails if index.html is out of date (used in CI)

Sources:
    src/index.html        page shell (markup) with /*@CSS@*/ and /*@JS@*/ slots
    src/css/app.css       all styles
    src/js/NN-*.js        the app, in numbered order; they share one scope
    src/shims/*.py        small Python modules the in-browser runner lacks
    content/curriculum.toml          the course map for both tracks
    content/python/NN-topic.toml     the lessons of one topic, in order

The output is a single self-contained file, so the site still works from
GitHub Pages with no server and nothing to install for students.
"""
from __future__ import annotations

import json
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SRC = ROOT / "src"
CONTENT = ROOT / "content"
OUT = ROOT / "index.html"

# The lesson data is generated and placed just before this file, which is the first one that uses it.
DATA_BEFORE = "07-practice.js"
LISTS_TOPIC = "05"  # its lessons are exposed as LISTS_ORDER (it also holds the hand-built "alias" lesson)


def js_value(value) -> str:
    """JSON is valid JavaScript; escape '</' so the data can never close the <script> tag."""
    return json.dumps(value, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/")


def load_toml(path: Path) -> dict:
    with path.open("rb") as f:
        return tomllib.load(f)


def load_lessons() -> tuple[dict, dict]:
    """Return (lessons by id, lesson ids by topic number)."""
    lessons: dict[str, dict] = {}
    topics: dict[str, list[str]] = {}
    for path in sorted((CONTENT / "python").glob("*.toml")):
        data = load_toml(path)
        topic = data["topic"]
        topics[topic] = []
        for entry in data["lesson"]:
            entry = dict(entry)
            lesson_id = entry.pop("id")
            topics[topic].append(lesson_id)
            if entry.pop("builtin", False):
                continue
            if lesson_id in lessons:
                raise SystemExit(f"{path.name}: duplicate lesson id {lesson_id!r}")
            entry["predict"].setdefault("fb", {})
            lessons[lesson_id] = entry
    return lessons, topics


def data_js() -> str:
    lessons, topics = load_lessons()
    curriculum = load_toml(CONTENT / "curriculum.toml")
    others = {n: ids for n, ids in topics.items() if n != LISTS_TOPIC}
    return (
        "/* generated by build.py from content/: do not edit here */\n"
        f"const TL_LESSONS = {js_value(lessons)};\n"
        f"const LISTS_ORDER = {js_value(topics.get(LISTS_TOPIC, []))};\n"
        f"const PY_TOPIC_LESSONS = {js_value(others)};\n"
        f"const CURRICULUM = {js_value(curriculum)};\n"
        f"const PROBLEMS = {js_value(load_problems())};\n"
    )


def load_problems() -> dict:
    """Practice problems by topic number, from content/problems/NN.toml."""
    out: dict[str, list[dict]] = {}
    for path in sorted((CONTENT / "problems").glob("*.toml")):
        data = load_toml(path)
        out[data["topic"]] = data["problem"]
    return out


def firebase_js():
    """The public Firebase web config, or null to use browser-only accounts."""
    path = ROOT / "src" / "config" / "firebase.json"
    if not path.exists():
        return "null"
    cfg = json.loads(path.read_text(encoding="utf-8") or "null")
    return js_value(cfg) if cfg else "null"


def shims_js() -> str:
    shims = {f"src/lib/{p.name}": p.read_text() for p in sorted((SRC / "shims").glob("*.py"))}
    return js_value(shims)


def build() -> str:
    parts = []
    for path in sorted((SRC / "js").glob("*.js")):
        if path.name == DATA_BEFORE:
            parts.append(data_js())
        parts.append(path.read_text())
    js = "\n".join(parts).replace("/*@SHIMS@*/null", shims_js()).replace("/*@FIREBASE@*/null", firebase_js())
    page = (SRC / "index.html").read_text()
    for slot, text in (("/*@CSS@*/", (SRC / "css" / "app.css").read_text()), ("/*@JS@*/", js)):
        if page.count(slot) != 1:
            raise SystemExit(f"src/index.html must contain {slot} exactly once")
        page = page.replace(slot, text.rstrip("\n"))
    return page


def main() -> None:
    page = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != page:
            raise SystemExit("index.html is out of date: run  python build.py  and commit the result")
        print("index.html is up to date")
        return
    OUT.write_text(page)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(page) // 1024} KB)")


if __name__ == "__main__":
    main()
